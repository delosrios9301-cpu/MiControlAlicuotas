import { strict as assert } from 'node:assert';
import { readFile } from 'node:fs/promises';
import { DOMParser } from '@xmldom/xmldom';
import { readAliquotXlsx } from '../web-import/xlsx-reader.js';
globalThis.DOMParser=DOMParser;
const data=await readFile('tests/prueba_xlsx_ficticia.xlsx');
const input={name:'prueba_xlsx_ficticia.xlsx',size:data.byteLength,async arrayBuffer(){return data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength)}};
const result=await readAliquotXlsx(input);
assert.equal(result.sheets.length,2);
assert.equal(result.rows.length,2);
assert.equal(result.rows[0].row,4);
assert.equal(result.rows[0].data.study,'ESTUDIO-PRUEBA');
assert.equal(result.rows[0].data.subject,'FICTICIO-1');
assert.equal(result.rows[0].data.barcode,'CODIGO-TEST');
assert.equal(result.rows[0].data.qty,2);
assert.equal(result.rows[0].data.sheetKind,'aliquot');
assert.equal(result.rows[1].data.qty,1);
assert.equal(result.rows[1].data.sheetKind,'exit');
await assert.rejects(readAliquotXlsx({...input,name:'prueba.xls'}),/\.xlsx/);
await assert.rejects(readAliquotXlsx({...input,size:20_000_000}),/15 MB/);
console.log('Prueba XLSX real: hojas, cadenas, datos y límites correctos.');
